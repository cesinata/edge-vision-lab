"""Generate web/src/content/copy.ts from docs/site-copy.md, so the site's words are never retyped.

    python scripts/make_site_copy.py

The only edit made to the text is replacing the drone recall figure with a placeholder that the
site fills from results/eval_torch.json (rule: every number comes from the results files). The
script fails if the figure in the copy does not match the results file rounded to 3 places.
"""
import json
import re
from pathlib import Path

R = Path(__file__).resolve().parents[1]
md = (R / "docs/site-copy.md").read_text()
ev = json.loads((R / "results/eval_torch.json").read_text())
recall = f"{ev['per_class']['drone']['recall']:.3f}"

sections = {}
cur = None
for line in md.splitlines():
    if line.startswith("## "):
        cur = line[3:].strip()
        sections[cur] = []
    elif cur is not None:
        sections[cur].append(line.rstrip())


def paras(lines):
    out, buf = [], []
    for ln in lines:
        if ln.strip() == "":
            if buf:
                out.append(" ".join(buf))
                buf = []
        else:
            buf.append(ln.strip())
    if buf:
        out.append(" ".join(buf))
    return out


def field(lines, name):
    for p in paras(lines):
        m = re.match(rf"\*\*{re.escape(name)}:\*\*\s*(.*)", p)
        if m:
            return m.group(1)
    raise KeyError(name)


def table(lines):
    rows = [ln for ln in lines if ln.startswith("|")]
    out = []
    for ln in rows[2:]:
        out.append([c.strip() for c in ln.strip().strip("|").split("|")])
    return out


S = sections
hdr = {m.group(1): m.group(2) for ln in S["Header"] for m in [re.match(r"- (Site name|Nav): (.*)", ln)] if m}
hero_p = paras(S["Hero"])
intro = hero_p[hero_p.index("**Intro**") + 1]
about = []
for p in paras(S["About this project"]):  # each question sits on the line above its answer, with no blank line
    m = re.match(r"\*\*(.*?)\*\*\s*(.*)", p)
    about.append({"q": m.group(1), "a": m.group(2)})
pl = S["The pipeline"]
sp = paras(S["Why the split is by scene"])
an = S["Anatomy of a vision board"]
dm = paras(S["Live demo"])
bullets = [ln for ln in S["Live demo"] if ln.startswith("- **")]  # consecutive lines, so not via paras()
lessons = S["Lessons"]
items = []
for ln in S["Results"]:  # list items sit on consecutive lines, so read lines, not paragraphs
    m = re.match(r"\d\. \*\*(.*?)\*\*\s*(.*)", ln)
    if m:
        items.append({"title": m.group(1), "text": m.group(2)})
assert len(items) == 3
assert recall in items[0]["text"], f"copy quotes a drone recall that differs from results/eval_torch.json ({recall})"
items[0]["text"] = items[0]["text"].replace(recall, "{{drone_recall}}")

copy = {
    "siteName": hdr["Site name"],
    "nav": [n.strip() for n in hdr["Nav"].split("·")],
    "hero": {"headline": field(S["Hero"], "Headline"), "intro": intro,
             "buttons": [b.strip() for b in field(S["Hero"], "Buttons").split("·")]},
    "about": {"title": "About this project", "items": about},
    "pipeline": {"title": "The pipeline", "heading": field(pl, "Heading"), "lead": field(pl, "Lead"),
                 "steps": [{"n": r[0], "title": r[1], "line": r[2]} for r in table(pl)]},
    "split": {"title": "Why the split is by scene", "paragraphs": sp[:2],
              "caption": re.match(r"Caption under the drawing:\s*(.*)", sp[2]).group(1)},
    "anatomy": {"title": "Anatomy of a vision board", "heading": field(an, "Heading"), "lead": field(an, "Lead"),
                "parts": [{"n": r[0], "part": r[1], "does": r[2]} for r in table(an)],
                "caption": re.match(r"Caption:\s*(.*)", paras(an)[-1]).group(1)},
    "demo": {"title": "Live demo", "heading": field(S["Live demo"], "Heading"),
             "intro": dm[1], "modelsIntro": dm[2],
             "models": [{"name": re.match(r"- \*\*(.*?)\*\*", b).group(1), "text": re.match(r"- \*\*.*?\*\*\s*(.*)", b).group(1)} for b in bullets],
             "warning": next(p for p in dm if p.startswith("Fair warning")),
             "readouts": re.match(r"Readouts:\s*(.*)", dm[-1]).group(1)},
    "lessons": {"title": "Lessons", "heading": field(lessons, "Heading"),
                "items": [{"n": r[0], "title": r[1], "blurb": r[2]} for r in table(lessons)]},
    "results": {"title": "Results", "heading": field(S["Results"], "Heading"), "lead": field(S["Results"], "Lead"),
                "items": items, "next": field(S["Results"], "Next steps")},
    "footer": paras(S["Footer"])[0],
}
assert len(copy["pipeline"]["steps"]) == 6 and len(copy["anatomy"]["parts"]) == 7 and len(copy["lessons"]["items"]) == 6
assert len(copy["demo"]["models"]) == 2 and len(copy["about"]["items"]) == 4

out = ("// Generated by scripts/make_site_copy.py from docs/site-copy.md. Do not edit by hand.\n"
       "export const COPY = " + json.dumps(copy, indent=2, ensure_ascii=False) + " as const;\n")
(R / "web/src/content/copy.ts").write_text(out)
print("wrote web/src/content/copy.ts;", sum(len(json.dumps(v)) for v in copy.values()), "chars of copy")
